// Bundle frontend/src into the panel file Home Assistant serves.
// The output is committed: HACS installs straight from the repository.
//
//   node build.mjs          production build (minified)
//   node build.mjs --dev    readable build for debugging
//
// Translations are written as separate content-hashed files
// (frontend/i18n/<lang>.<hash>.json) so the panel downloads only the active
// language, and browsers can cache every file until its content changes.
import { build } from "esbuild";
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const outDir = here("../custom_components/homesec/frontend/");
const dev = process.argv.includes("--dev");

// ── Locale files ────────────────────────────────────────────────────────────
const i18nOut = `${outDir}i18n/`;
rmSync(i18nOut, { recursive: true, force: true });
mkdirSync(i18nOut, { recursive: true });
const localeFiles = {};
for (const file of readdirSync(here("src/i18n/")).filter((f) => f.endsWith(".json")).sort()) {
  const lang = file.slice(0, -".json".length);
  const json = JSON.stringify(JSON.parse(readFileSync(here(`src/i18n/${file}`), "utf8")));
  const hash = createHash("sha256").update(json).digest("hex").slice(0, 10);
  const name = `${lang}.${hash}.json`;
  writeFileSync(`${i18nOut}${name}`, json);
  localeFiles[lang] = `i18n/${name}`;
}

// ── Panel bundle ────────────────────────────────────────────────────────────
await build({
  entryPoints: [here("src/panel.js")],
  outfile: `${outDir}homesec-panel.js`,
  bundle: true,
  format: "esm",
  target: "es2020",
  minify: !dev,
  legalComments: "eof",
  define: { __HSA_LOCALE_FILES__: JSON.stringify(localeFiles) },
  banner: { js: "// Generated by frontend/build.mjs from frontend/src - do not edit by hand." },
  logLevel: "info",
});
