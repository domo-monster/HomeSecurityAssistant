// Bundle frontend/src into the panel file Home Assistant serves.
// The output is committed: HACS installs straight from the repository.
import { build } from "esbuild";
import { fileURLToPath } from "node:url";

const out = fileURLToPath(new URL("../custom_components/homesec/frontend/homesec-panel.js", import.meta.url));

await build({
  entryPoints: [fileURLToPath(new URL("src/panel.js", import.meta.url))],
  outfile: out,
  bundle: true,
  format: "esm",
  target: "es2020",
  minify: process.argv.includes("--minify"),
  legalComments: "eof",
  banner: { js: "// Generated by frontend/build.mjs from frontend/src - do not edit by hand." },
  logLevel: "info",
});
